/**
 * Закрытый режим: бот отвечает только владельцу.
 *
 * Нужен, когда доступ выдаётся платно или проект показывают ограниченному
 * кругу. Все остальные — и те, кому доступ уже был выдан, и новички — видят
 * одну и ту же заглушку и ничего больше сделать не могут.
 *
 * Включается переменной LOCKED=on. Отдельным выключателем, а не удалением
 * ролей: снять ограничение надо одной строкой, не трогая данные людей.
 */

import { ROLE_OWNER, User } from "./types";

/** Текст заглушки. Один на все каналы — человек не должен видеть разные формулировки. */
export const LOCKED_TEXT =
  "🔒 Бесплатный доступ закончился\n\n" +
  "Чтобы продолжить пользоваться Сарой, напишите администратору — он откроет доступ.";

/** Включён ли закрытый режим. */
export function locked(env: { LOCKED?: string }): boolean {
  return (env.LOCKED ?? "").trim().toLowerCase() === "on";
}

/**
 * Показывать ли заглушку этому человеку.
 *
 * Владелец работает как обычно: иначе включённый режим отрезал бы и того, кто
 * должен выдавать доступ.
 */
export function lockedFor(env: { LOCKED?: string }, user: User | null): boolean {
  if (!locked(env)) return false;
  return user?.role !== ROLE_OWNER;
}

/** То же для MAX, где владельца узнают по id в мессенджере, а не по роли. */
export function lockedForMax(env: { LOCKED?: string }, isOwner: boolean): boolean {
  return locked(env) && !isOwner;
}
